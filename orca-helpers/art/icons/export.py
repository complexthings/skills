"""Export the picked icons for the Wave band and the Prompt Band.

Reads orca-helpers/art/icons/picks.json, cuts each picked icon's
PNG (an anim's sheet into frames) and writes, under orca-helpers/hooks/assets/:
one RGBA PNG per frame (`wave_0.png`.., `check_0.png`, `upcoming_0.png`,
`flag_0.png`.., `orca_0.png`..) and `icons.ts`, the same pixels as SVG <rect>
markup for the Desktop bands.

Run from the repo root: python3 orca-helpers/art/icons/export.py
"""

import json
import pathlib
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
PICKS = ROOT / "orca-helpers/art/icons/picks.json"
OUT = ROOT / "orca-helpers/hooks/assets"
ROLES = ("wave", "check", "upcoming", "flag", "orca")


def chunks(data):
    i = 8
    while i < len(data):
        (n,) = struct.unpack(">I", data[i : i + 4])
        yield data[i + 4 : i + 8], data[i + 8 : i + 8 + n]
        i += 12 + n


def decode(path):
    """An indexed PNG (pxl's output) or an 8-bit RGBA one as rows of (r, g, b, a) tuples."""
    idat, trns = b"", b""
    for kind, body in chunks(path.read_bytes()):
        if kind == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
            assert color == 3 or (color, depth) == (6, 8), f"{path}: expected an indexed or RGBA PNG"
        elif kind == b"PLTE":
            plte = [tuple(body[i : i + 3]) for i in range(0, len(body), 3)]
        elif kind == b"tRNS":
            trns = body
        elif kind == b"IDAT":
            idat += body
    raw = zlib.decompress(idat)
    bpp = 4 if color == 6 else 1
    stride = w * 4 if color == 6 else (w * depth + 7) // 8
    prev, rows, i = bytearray(stride), [], 0
    for _ in range(h):
        ftype, line = raw[i], bytearray(raw[i + 1 : i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b, c = prev[x], prev[x - bpp] if x >= bpp else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 255
            elif ftype == 2:
                line[x] = (line[x] + b) & 255
            elif ftype == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif ftype == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        prev = line
        if color == 6:
            rows.append([tuple(line[x : x + 4]) for x in range(0, stride, 4)])
            continue
        per = 8 // depth
        idx = [(line[x // per] >> (8 - depth * (x % per + 1))) & ((1 << depth) - 1) for x in range(w)]
        rows.append([(*plte[k], trns[k] if k < len(trns) else 255) for k in idx])
    return rows


def encode(rows):
    w, h = len(rows[0]), len(rows)
    raw = b"".join(b"\0" + bytes(v for px in row for v in px) for row in rows)

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def svg(rows):
    """One <rect> per horizontal run of one color; transparent pixels draw nothing."""
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            end = x
            while end + 1 < len(row) and row[end + 1] == row[x]:
                end += 1
            r, g, b, a = row[x]
            if a:
                opacity = "" if a == 255 else f' fill-opacity="{a / 255:.2f}"'
                rects.append(f'<rect x="{x}" y="{y}" width="{end - x + 1}" height="1" fill="#{r:02x}{g:02x}{b:02x}"{opacity}/>')
            x = end + 1
    w, h = len(rows[0]), len(rows)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" shape-rendering="crispEdges">{"".join(rects)}</svg>'


def frames(source, name):
    sheet = source / "anims" / f"{name}.json"
    if not sheet.exists():
        return [decode(source / "sprites" / f"{name}.png")]
    rows = decode(source / "anims" / f"{name}.png")
    boxes = [f["frame"] for f in json.loads(sheet.read_text())["frames"].values()]
    return [[r[b["x"] : b["x"] + b["w"]] for r in rows[b["y"] : b["y"] + b["h"]]] for b in boxes]


def main():
    picks = json.loads(PICKS.read_text())
    source = ROOT / picks["iconSource"]
    OUT.mkdir(parents=True, exist_ok=True)
    markup = {}
    for role in ROLES:
        name = picks["icons"][role]
        cut = frames(source, name)
        for n, rows in enumerate(cut):
            (OUT / f"{role}_{n}.png").write_bytes(encode(rows))
        markup[role] = (name, [svg(rows) for rows in cut])
    lines = [
        "// Generated by orca-helpers/art/icons/export.py from orca-helpers/art/icons/picks.json; do not edit.",
        "// The picked icons' pixels as SVG <rect> markup, one string per frame,",
        "// matching the PNG frames beside this file.",
        "",
        "export const FRAMES = {",
    ]
    for role, (name, svgs) in markup.items():
        lines.append(f"  // {name}")
        lines.append(f"  {role}: [")
        lines += [f"    {json.dumps(s)}," for s in svgs]
        lines.append("  ],")
    lines += ["} as const", ""]
    (OUT / "icons.ts").write_text("\n".join(lines))
    print({role: len(svgs) for role, (_, svgs) in markup.items()})


if __name__ == "__main__":
    main()
