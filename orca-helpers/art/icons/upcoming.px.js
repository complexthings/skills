// Upcoming-step icons, 18x18 static, gray. Mid gray a=#959595 (reads on dark and light),
// shade A=#595959 for depth. Deliberately quiet: thin strokes, no fills.
pal({ a: "#959595", A: "#595959" })

sprite("upcoming_1", { w: 18, h: 18 }, ring(9, 9, 6, "a"))            // hollow ring

sprite("upcoming_2", { w: 18, h: 18 },                                  // ellipsis
  rect(2, 8, 3, 3, "a"), rect(7, 8, 3, 3, "a"), rect(12, 8, 3, 3, "a"))

sprite("_hg", `
  ................
  ..aaaaaaaaaaaa..
  ..aaaaaaaaaaaa..
  ...a........a...
  ....a......a....
  .....a....a.....
  ......aAAa......
  .......aa.......
  .......aa.......
  ......a..a......
  .....a.AA.a.....
  ....a.AAAA.a....
  ...a.AAAAAA.a...
  ..aaaaaaaaaaaa..
  ..aaaaaaaaaaaa..`)
sprite("upcoming_3", { w: 18, h: 18 }, stamp("_hg", 1, 1))               // hourglass

sprite("upcoming_4", { w: 18, h: 18 }, (c) => {                         // dashed circle
  c.ring(9, 9, 7, "a")
  for (let y = 0; y < 18; y++) for (let x = 0; x < 18; x++) {
    const ang = Math.atan2(y - 9, x - 9) + Math.PI
    if (Math.floor(ang / (Math.PI / 8)) % 2) c.px(x, y, "_")
  }
})

sprite("_ch", `
  .....aa.....
  ......aa....
  .......aa...
  ........aa..
  .......aa...
  ......aa....
  .....aa.....`)
sprite("upcoming_5", { w: 18, h: 18 }, stamp("_ch", 2, 5))               // chevron
