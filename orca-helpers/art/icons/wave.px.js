// 5: wave with foam and spray flying off the crest
anim("wave_5", { w: S, h: S, frames: 8, fps: 8 }, (c) => {
  for (let x = 0; x < S; x++) {
    const y = Math.round(12 + 2.8 * Math.sin(T * (x / S - c.phase)))
    col(c, x, y, S - 1, "b")
    c.px(x, clampY(y), "w")
    c.px(x, clampY(y + 1), "l")
    col(c, x, y + 4, S - 1, "d")
  }
  // spray: 3 droplets, each on an arc over the loop, offset in phase
  for (let i = 0; i < 3; i++) {
    const t = (c.phase + i / 3) % 1
    const x = 4 + i * 5 + Math.round(t * 3)
    const y = Math.round(9 - 7 * 4 * t * (1 - t))
    c.rect(x, clampY(y), 2, 2, t > 0.5 ? "l" : "w")
    c.px(x, clampY(y), "l")
  }
})

