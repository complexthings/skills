// pose -> 18 full rows (top-padded to 16, then the sea)
const rows6 = (k) => {
  const r = poses[k].split("\n").map((l) => l.trim()).filter(Boolean)
  return [...Array(16 - r.length).fill("."), ...r, "b".repeat(S), "d".repeat(S)].map((l) => l.padEnd(S, "."))
}
const at = (r, x, y) => (y >= 0 && y < S && x >= 0 && x < S ? r[y][x] : ".")
// paint a pose shifted by dx; key(r, x, y) picks the color for an opaque pixel (null = skip)
const paint = (k, dx, key) => (c) => {
  const r = rows6(k)
  for (let y = 0; y < S; y++) for (let x = 0; x < S; x++) {
    const sx = y < 16 ? x - dx : x
    if (at(r, sx, y) === ".") continue
    const v = key(r, sx, y)
    if (v) c.px(x, y, v)
  }
}
const edge = (r, x, y) => [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([u, v]) => at(r, x + u, y + v) === "." && y + v < 16)
const loop6 = ["curl", "crash", "wash", "settle", "flat", "swell", "rise", "peak", "pitch"]
const hold6 = (k) => (k === "curl" || k === "flat" ? { hold: 2 } : {})
const breaker = (name, opts, dxs, key) =>
  anim(name, { w: S, h: S, fps: 7, ...opts }, ...loop6.map((k, i) => frame(hold6(k), paint(k, dxs ? dxs[i] : 0, key))))
const asIs = (r, x, y) => r[y][x]

// 6: classic breaker in place: swell rises, curls over a dark barrel, crashes with spray, flattens
breaker("wave_6", {}, null, asIs)

// 7: line art: only the silhouette edge (band blue, so it holds on white), foam and barrel; hollow body
breaker("wave_7", {}, null, (r, x, y) => {
  const k = r[y][x]
  if (y >= 16 || k === "d" || k === "w") return k
  return edge(r, x, y) ? "b" : null
})

// 8: travelling breaker: the swell enters from the left and crashes on the right; the flat frame hides the wrap
breaker("wave_8", {}, [2, 3, 4, 5, 0, -4, -3, -1, 1], asIs)

// 9: high contrast: a navy rim around the body so the shape holds on white; no pale tints
