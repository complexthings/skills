const T = Math.PI * 2
const S = 18
const clampY = (y) => Math.max(0, Math.min(S - 1, y))
// fill column x from y0 down to y1 (inclusive)
const col = (c, x, y0, y1, k) => { for (let y = Math.round(y0); y <= y1; y++) if (y >= 0 && y < S) c.px(x, y, k) }

// 1: rolling sine line (thick ribbon with light crest edge)
anim("wave_1", { w: S, h: S, frames: 8, fps: 8 }, (c) => {
  const f = (x) => 9 + 4.5 * Math.sin(T * (x / S - c.phase))
  for (let x = 0; x < S; x++) {
    const ya = f(x - 0.5), yb = f(x + 0.5)
    const top = Math.round(Math.min(ya, yb)), bot = Math.round(Math.max(ya, yb))
    c.px(x, clampY(top - 1), "l")
    col(c, x, top, bot + 1, "b")
    c.px(x, clampY(bot + 2), "d")
  }
})

// 2: three stacked wave bands scrolling at different speeds
anim("wave_2", { w: S, h: S, frames: 6, fps: 7 }, (c) => {
  const band = (base, amp, dir, mult, k, top) => {
    for (let x = 0; x < S; x++) {
      const y = Math.round(base + amp * Math.sin(T * (mult * (x / S) - dir * c.phase)))
      col(c, x, y, S - 1, k)
      if (top) c.px(x, clampY(y), top)
    }
  }
  band(5, 1.6, 1, 1, "d")
  band(9, 1.8, -1, 1, "b", "l")
  band(13, 1.6, 1, 1, "l", "w")
})

// 3: a single swell that bobs up and down over a calm surface
anim("wave_3", { w: S, h: S, frames: 8, fps: 8 }, (c) => {
  const h = 3.5 + 2.5 * Math.sin(T * c.phase)
  for (let x = 0; x < S; x++) {
    const y = Math.round(12 - h * Math.exp(-(((x - 8.5) / 3.6) ** 2)) + 0.8 * Math.sin(T * (x / S + c.phase)))
    col(c, x, y, S - 1, "b")
    c.px(x, clampY(y), "l")
    col(c, x, y + 4, S - 1, "d")
  }
})

